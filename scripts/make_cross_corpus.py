#!/usr/bin/env python3
"""Assemble the side-by-side reading of the two corpora.

Each corpus gets its own REPORT.md, and a gap answered on one corpus is not
answered in general. This writes the comparison the two reports defer to: where
they agree, where they disagree, and which disagreements are explained by a
difference in the corpora rather than in the traffic.

The output is spliced into README.md between the marker comments, so the README
never drifts from the JSON.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

BEGIN = "<!-- BEGIN cross-corpus (generated by scripts/make_cross_corpus.py) -->"
END = "<!-- END cross-corpus -->"


# Earlier runs were launched with the short corpus key as the name. Map those
# to the display name rather than rewriting the run configs, which are a record
# of what was actually run.
DISPLAY = {"ustc": "USTC-TFC2016", "iscx": "ISCX VPN-nonVPN"}


def load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def read(results: Path) -> dict:
    sweeps = sorted(results.glob("e2_budget_sweep_*.json"))
    e2 = next((load(p) for p in sweeps if not p.stem.endswith("_zero")), None)
    e3 = load(results / "e3_stratified_uncapped_wang1d_784B.json") \
        or load(results / "e3_stratified_wang1d_784B.json")
    return {
        "cfg": load(results / "run_config.json") or {},
        "stats": load(results / "corpus_stats.json") or {},
        "e1": load(results / "e1_baseline_and_leakage.json"),
        "e2": e2,
        "e3": e3,
        "pad": next((load(p) for p in sorted(results.glob("padding_controls_*.json"))), None),
        "gran": load(results / "ablation_granularity.json"),
        "ports": load(results / "port_dependence_wang1d.json"),
        "ss": load(results / "split_strategy.json"),
    }


def padding_paragraph(corpora: dict, names: list) -> str:
    """State the padding attribution at the strength the numbers support.

    The two arms are only worth separating where the combined effect is large
    enough for three seeds to tell them apart. Where it is not, the control
    returns a null result, and saying so is the difference between a finding
    and a coincidence.
    """
    lines, conclusive = [], []
    for n in names:
        attr = (corpora[n].get("pad") or {}).get("mask_attribution")
        if not attr:
            continue
        rep, pad = attr["representation_effect"], attr["padding_symbol_effect"]
        noise = attr["seed_noise"]
        if abs(rep) > noise:
            conclusive.append(n)
            lines.append(f"on {n} the representation is worth {rep:+.4f} and the "
                         f"padding symbol {pad:+.4f}, against {noise:.4f} of seed noise")
        else:
            lines.append(f"on {n} the whole effect is {rep + pad:+.4f} against "
                         f"{noise:.4f} of seed noise, too small to split")

    head = ("**The padding gain is the representation, not the padding symbol, "
            "where the effect is large enough to tell.** ")
    body = "; ".join(lines) + "."
    if len(conclusive) == len(names):
        tail = (" So a paper reporting the combined figure as a padding-aware result "
                "would be wrong by nearly the whole effect, on either corpus.")
    elif conclusive:
        tail = (f" So the attribution is carried by {', '.join(conclusive)}, where the "
                f"effect is big enough to decompose. Elsewhere the control returns a "
                f"null result: that is not evidence the padding symbol helps, it is "
                f"the absence of evidence either way, and it is reported as such "
                f"rather than pooled into an average that would look conclusive.")
    else:
        tail = (" So this study cannot attribute the effect on either corpus, and says "
                "so rather than quoting the combined figure.")
    return head + body[0].upper() + body[1:] + tail


def length_paragraph(corpora: dict, names: list) -> str:
    """Whether anything survives once flow length can no longer separate classes.

    This is the control the whole study points at, and it is the place the two
    corpora disagree most sharply. Both answers rest on a test set in the low
    hundreds, so the direction is reported and the magnitude is not.
    """
    survived, collapsed, lines = [], [], []
    for n in names:
        pad = corpora[n].get("pad") or {}
        lb, cell = pad.get("length_balance"), (pad.get("controls") or {}).get("length_balanced")
        if not lb or not cell:
            continue
        got = cell["macro_f1"]["mean"]
        chance = lb["chance_within_balanced_set"]
        n_te = lb["n_test"]
        (survived if got > chance + max(2 * cell["macro_f1"]["std"], 0.05)
         else collapsed).append(n)
        lines.append(f"{n} scores {got:.4f} against a {chance:.4f} chance rate on "
                     f"{n_te} test sessions")
    if not lines:
        return ("**The length-balanced control was not formed on either corpus**, so "
                "nothing here speaks to whether flow length alone carries the signal.")
    body = "**Equalising flow length destroys the signal on one corpus and not the "            "other.** " + "; ".join(lines) + "."
    if survived and collapsed:
        body += (f" So on {', '.join(survived)} content still separates the classes "
                 f"with length held fixed, while on {', '.join(collapsed)} very little "
                 f"does, which would put much of that corpus's apparent accuracy on "
                 f"flow length rather than on content. This is the sharpest "
                 f"disagreement between the two, and it is a reason not to generalise "
                 f"a padding or budget result from one corpus to the other. Both "
                 f"figures rest on a test set in the low hundreds, so the direction is "
                 f"what should be read here, not the magnitude.")
    elif survived:
        body += (" Content survives on both, so neither budget curve is simply a "
                 "length curve under another name.")
    else:
        body += (" Little survives on either, which puts a large share of the apparent "
                 "signal on flow length on both corpora.")
    return body


def granularity_paragraph(corpora: dict, names: list) -> str:
    """Whether the unit of analysis matters, and whether the corpora agree.

    A flow is shorter than the session it came from, so at a fixed byte budget
    the flow setting is also the less truncated one. That makes a flow win
    uninterpretable and a flow loss informative, which is worth saying once
    across both corpora rather than twice inside them.
    """
    rows, verdicts = [], {}
    for n in names:
        g = corpora[n].get("gran")
        if not g:
            continue
        verdicts[n] = g["verdict"]
        rows.append(f"on {n} the difference is {g['delta_macro_f1']:+.4f} macro-F1 "
                    f"against {g['seed_noise']:.4f} of seed noise ({g['verdict']})")
    if not rows:
        return ("**Step 10(iii) granularity was not run on either corpus**, so nothing "
                "here speaks to whether the unit of analysis matters.")
    decided = [n for n, v in verdicts.items() if v != "inconclusive"]
    sentence = "; ".join(rows) + "."
    body = ("**The unit of analysis matters on one corpus and not measurably "
            "on the other.** " + sentence[0].upper() + sentence[1:])
    if len(decided) == 1 and verdicts[decided[0]] == "session better":
        body += (f" Only {decided[0]} separates them, and it does so in the direction "
                 f"the confound argues against: flows are shorter than their parent "
                 f"sessions, so at a fixed budget the flow setting sees a larger share "
                 f"of each unit and still loses. Pairing the two directions of a "
                 f"conversation carries information that reading them separately does "
                 f"not, at least where the classes are hard enough for it to show. "
                 f"On the easier corpus everything is near ceiling and the question "
                 f"does not arise.")
    elif not decided:
        body += (" Neither corpus separates them, so this study has nothing to say "
                 "about granularity beyond that the choice did not matter at these "
                 "budgets.")
    return body


def row(label: str, cells: list[str]) -> str:
    return "| " + " | ".join([label] + cells) + " |"


def build(corpora: dict[str, dict]) -> str:
    names = list(corpora)
    head = [
        "## What the two corpora say together", "",
        "Each corpus has its own report under `results/`. This is the comparison "
        "those reports defer to. Every row is generated from the JSON in both "
        "directories.", "",
        row("", [f"**{n}**" for n in names]),
        row("---", ["---"] * len(names)),
    ]
    out = list(head)

    def cells(fn) -> list[str]:
        values = []
        for n in names:
            try:
                values.append(fn(corpora[n]))
            except (KeyError, TypeError, ValueError, ZeroDivisionError):
                values.append("n/a")
        return values

    out += [
        row("sessions", cells(lambda d: f"{d['stats']['n_sessions']:,}")),
        row("classes", cells(lambda d: str(d['stats']['n_classes']))),
        row("byte budget where the sweep saturates",
            cells(lambda d: f"**{d['e2']['bytes_saturation']['at']}**")),
        row("packet budget where the sweep saturates",
            cells(lambda d: f"**{d['e2']['packets_saturation']['at']}**")),
        row("best macro-F1 over the whole sweep",
            cells(lambda d: f"{max(c['macro_f1']['mean'] for c in d['e2']['bytes'].values()):.4f}")),
        row("macro-F1 at the smallest budget tried",
            cells(lambda d: f"{list(d['e2']['bytes'].values())[0]['macro_f1']['mean']:.4f}")),
        row("padded rather than truncated at 1024 B",
            cells(lambda d: f"{d['stats']['padded_fraction_at_budget']['1024B']:.1%}")),
        row("definitely not encrypted",
            cells(lambda d: f"{d['stats']['definitely_not_encrypted_fraction']:.1%}")),
        row("confirmed TLS",
            cells(lambda d: f"{d['stats']['confirmed_tls_fraction']:.1%}")),
        row("of those handshakes, deprecated suites",
            cells(lambda d: f"{d['stats']['tls']['deprecated_fraction']:.1%}")),
        row("ports-only probe against chance",
            cells(lambda d: f"{d['e1']['leakage']['probes']['ports']['accuracy']['mean']:.4f} "
                            f"vs {d['e1']['leakage']['majority_class_rate']:.4f}")),
        row("largest macro-F1 lost to masking ports",
            cells(lambda d: f"{d['ports']['summary']['largest_drop']:+.4f} at "
                            f"{max(d['ports']['budgets'].items(), key=lambda kv: kv[1]['macro_f1_lost_to_port_masking'])[0]}")),
        row("concealment gap (weighted − macro F1)",
            cells(lambda d: f"{d['e3']['overall']['weighted_f1'] - d['e3']['overall']['macro_f1']:+.4f}")),
        row("classes below 0.05 F1",
            cells(lambda d: ", ".join(f"`{c}`" for c in d['e3']['failed_classes']) or "none")),
        row("classes split temporally, not group-wise",
            cells(lambda d: f"{d['stats']['split_strategy_counts'].get('temporal', 0)} of "
                            f"{sum(d['stats']['split_strategy_counts'].values())}")),
        row("macro-F1 with flow length equalised",
            cells(lambda d: f"{d['pad']['controls']['length_balanced']['macro_f1']['mean']:.4f} "
                            f"(chance {d['pad']['length_balance']['chance_within_balanced_set']:.4f}, "
                            f"n={d['pad']['length_balance']['n_test']})")),
        row("session against unidirectional flow",
            cells(lambda d: f"{d['gran']['delta_macro_f1']:+.4f} ({d['gran']['verdict']})")),
        row("padding: representation effect",
            cells(lambda d: f"{d['pad']['mask_attribution']['representation_effect']:+.4f}")),
        row("padding: PAD-symbol effect",
            cells(lambda d: f"{d['pad']['mask_attribution']['padding_symbol_effect']:+.4f}")),
        "",
    ]

    out += ["### What replicates", "",
            "**Every reviewed budget sits at or past saturation, on both corpora.** The "
            "saturation point differs, in that the harder corpus saturates *earlier*, "
            "not later, but no paper budget falls below it in either case. This is the "
            "study's main result and it is the one that replicates most cleanly.", "",
            padding_paragraph(corpora, names), "",
            "**Most of what the model reads at a literature budget is padding, and "
            "nobody reports it.** The ISCX figure matches P8's implied ~87% from "
            "entirely independent preprocessing, which is the closest thing here to an "
            "external check on the pipeline.", "",
            "**The leakage gate passes on both**, so anonymisation left no usable "
            "identifier signal, and on both the ports shortcut exists but is redundantly "
            "encoded rather than load-bearing.", "",
            "### What does not replicate", "",
            "**The concealment gap changes sign.** On USTC a weighted average flatters "
            "the per-class picture, which is the direction Phase 1 anticipated. On ISCX "
            "it is strongly negative: the frequent classes are the hard ones, so the "
            "weighted average reports *worse* than the macro average. The headline "
            "number misleads either way, but a paper that assumes the sign can correct "
            "in the wrong direction.", "",
            "**The ports shortcut is far stronger on USTC.** A ports-only probe is close "
            "to the full model there and much weaker on ISCX. Neither is load-bearing, "
            "but the risk a reviewer should check is corpus-dependent.", "",
            length_paragraph(corpora, names), "",
            granularity_paragraph(corpora, names), "",
            "### The disagreement that is probably not about traffic", ""]

    pairs = [(n, corpora[n]["stats"].get("split_strategy_counts") or {}) for n in names]
    frags = []
    for n, counts in pairs:
        total = sum(counts.values()) or 1
        frags.append(f"{n} splits {counts.get('temporal', 0)} of {total} classes "
                     f"temporally")
    out += ["The two corpora differ in measured difficulty by a wide margin, and they "
            "also differ in how their classes can be split: " + "; ".join(frags) + ". "
            "A temporal split draws train and test from the same capture; a group split "
            "holds whole captures out. The first is the easier problem.", "",
            "Those two differences point the same way, and this study cannot separate "
            "them: the corpus with more temporal splits is also the one that scores "
            "higher. So the difficulty gap between the corpora should **not** be read as "
            "a statement about the traffic. It is a reason to be sceptical of any "
            "cross-corpus accuracy comparison, including the ones in the reviewed "
            "papers, that does not say how its splits were formed.", "",
            "This is a limitation of the present study, not a finding against the "
            "literature, and it is measurable within one corpus even though it is not "
            "measurable between them.", ""]
    out += _split_strategy_paragraph(corpora)
    return "\n".join(out)


def _split_strategy_paragraph(corpora: dict[str, dict]) -> list[str]:
    """What varying only the split boundary turned out to be worth.

    Written against whichever corpus could host the experiment, because only
    one can: the other's classes almost all come from a single capture file.
    """
    carrier = next((n for n in corpora if (corpora[n].get("ss") or {}).get("arms")),
                   None)
    if not carrier:
        return []
    ss = corpora[carrier]["ss"]
    arms = ss["arms"]
    g, rand, temp = arms["group"], arms.get("random"), arms.get("temporal")
    if not rand:
        return []
    out = [f"On the {len(ss['classes'])} {carrier} classes that have enough capture "
           f"files to be split either way, that experiment has now been run: the "
           f"classes, the budget, the model, the epochs, the seeds and the per-class "
           f"split sizes are held fixed and only the train/test boundary moves. "
           f"A **random within-capture split scores "
           f"{rand['macro_f1']['mean']:.4f} macro-F1 against "
           f"{g['macro_f1']['mean']:.4f} for a group-wise one**: "
           f"{rand['inflation_macro_f1']:+.4f}, against "
           f"{rand['seed_noise']:.4f} of seed noise. A paper that does not state its "
           f"split policy is most likely reporting the first number."]
    if temp and temp.get("verdict") == "inconclusive":
        out[0] += (f" The temporal fallback used here is not measurably worse than "
                   f"group-wise ({temp['inflation_macro_f1']:+.4f} against "
                   f"{temp['seed_noise']:.4f}), so the per-corpus numbers above are "
                   f"not inflated that way, but the cross-corpus comparison stays "
                   f"confounded, because the two corpora differ in how many classes "
                   f"can be split group-wise at all.")
    return out + [""]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", nargs="+", required=True,
                    help="results directories, as name=path or just path")
    ap.add_argument("--readme", default="README.md")
    args = ap.parse_args()

    corpora = {}
    for item in args.results:
        name, _, path = item.partition("=")
        if not path:
            path, name = name, Path(name).name.upper()
        data = read(Path(path))
        label = data["cfg"].get("corpus_name") or name
        corpora[DISPLAY.get(label.lower(), label)] = data

    block = f"{BEGIN}\n\n{build(corpora)}\n{END}"
    readme = Path(args.readme)
    text = readme.read_text()
    if BEGIN in text and END in text:
        before = text[:text.index(BEGIN)]
        after = text[text.index(END) + len(END):]
        readme.write_text(before + block + after)
        print(f"replaced the cross-corpus block in {readme}")
    else:
        readme.write_text(text.rstrip() + "\n\n" + block + "\n")
        print(f"appended the cross-corpus block to {readme}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
